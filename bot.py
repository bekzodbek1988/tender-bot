def create_guarantee_letter(filename, doc_data):
    doc = docx.Document()
    
    # Саҳифа майдонлари (Margins)
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(0.75)
        section.bottom_margin = Inches(0.75)
        section.left_margin = Inches(0.8)
        section.right_margin = Inches(0.8)

    # 1. Корхона Реквизитлари Бланкаси
    add_header_requisites(doc)

    # 2. Сана ва Манзил
    p_meta = doc.add_paragraph()
    p_meta.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run_meta = p_meta.add_run("«___» _________ 2026 йил\n«Буюртмачи» АЖга")
    run_meta.font.name = 'Times New Roman'
    run_meta.font.size = Pt(14)
    run_meta.font.bold = True

    # 3. Ҳужжат номи/Сарлавҳаси (14 pt)
    p_title = doc.add_paragraph()
    format_paragraph(p_title, doc_data["title"], bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=12)

    # 4. Асосий Матн (14 pt)
    for text in doc_data["content"]:
        p_content = doc.add_paragraph()
        format_paragraph(p_content, text, space_after=8)

    # 5. Имзо қисми (14 pt)
    doc.add_paragraph() # Жой ташлаш
    p_sign = doc.add_paragraph()
    p_sign.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run_sign = p_sign.add_run("«DOBUS QURILISH» МЧЖ Директори:   _________________  Рузиев Э. Б.")
    run_sign.font.name = 'Times New Roman'
    run_sign.font.size = Pt(14)
    run_sign.font.bold = True

    # Сақлаш
    doc.save(f"{filename}.docx")
    print(f"Ҳужжат муваффақиятли яратилди: {filename}.docx")

# Барча 12 та файлни автоматик генерация қилиш
for name, data in DOCUMENTS.items():
    create_guarantee_letter(name, data)
